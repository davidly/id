"""Builds the derived regression fixtures in tests/images.

Run from any directory: python tests/make-fixtures.py
The baseline is generated by regenerate.ps1. Container fixtures use synthetic metadata
and placeholder image data where decoding pixels is unnecessary.
"""
import gzip
