# ---------------------------------------------------------------- XMP and EXIF variants


def with_xmp(packet):
    plain = read('plain.jpg')
    return plain[:2] + segment(0xe1, b'http://ns.adobe.com/xap/1.0/\0' + packet) + plain[2:]


def with_user_comment(comment, little_endian):
    """plain.jpg plus an EXIF APP1 whose Exif IFD holds only a UserComment."""
    e = '<' if little_endian else '>'
    tiff = (b'II' if little_endian else b'MM') + struct.pack(e + 'HI', 42, 8)
    exif_ifd = 8 + 2 + 12 + 4
    data_offset = exif_ifd + 2 + 12 + 4
    ifd0 = struct.pack(e + 'H', 1) + struct.pack(e + 'HHII', 0x8769, 4, 1, exif_ifd) + struct.pack(e + 'I', 0)
    exif = struct.pack(e + 'H', 1) + struct.pack(e + 'HHII', 0x9286, 7, len(comment), data_offset) + \
        struct.pack(e + 'I', 0)
    plain = read('plain.jpg')
    return plain[:2] + segment(0xe1, b'Exif\0\0' + tiff + ifd0 + exif + comment) + plain[2:]


