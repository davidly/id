HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'images')


def read(name):
    with open(os.path.join(HERE, name), 'rb') as f:
        return f.read()


def write(name, data):
    with open(os.path.join(HERE, name), 'wb') as f:
        f.write(data)


def xmp(properties, extra_ns=''):
    return ('<x:xmpmeta xmlns:x="adobe:ns:meta/"><rdf:RDF '
            'xmlns:rdf="http://www.w3.org/1999/02/22-rdf-syntax-ns#">'
            '<rdf:Description rdf:about="" '
            'xmlns:Iptc4xmpExt="http://iptc.org/std/Iptc4xmpExt/2008-02-29/" '
            + extra_ns + ' ' + properties + '/></rdf:RDF></x:xmpmeta>').encode()


GENERATIVE_XMP = xmp('Iptc4xmpExt:DigitalSourceType='
                     '"http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia"')

# ---------------------------------------------------------------- JPEG


def segment(marker, payload):
    return bytes([0xff, marker]) + struct.pack('>H', len(payload) + 2) + payload


def generated_jumbf():
    """A synthetic unsigned box for the heuristic C2PA scan."""
    uuid = bytes.fromhex('6332706100110010800000aa00389b71')
    uri = b'http://cv.iptc.org/newscodes/digitalsourcetype/trainedAlgorithmicMedia'
    cbor = b'\xa1\x71digitalSourceType\x78' + bytes([len(uri)]) + uri
    return box(b'jumb', box(b'jumd', uuid + b'\x03c2pa\0') + box(b'cbor', cbor))


def make_jpeg_fixtures():
    plain = read('plain.jpg')
    store = generated_jumbf()
    prefix = b'JP\0\x01'
    write('c2pa-only-generator.jpg', plain[:2] +
          segment(0xeb, prefix + struct.pack('>I', 1) + store) + plain[2:])
    # Split inside the source type and repeat the box header in the continuation.
    split = store.index(b'trainedAlgorithmicMedia') + 7
    first = segment(0xeb, prefix + struct.pack('>I', 1) + store[:split])
    second = segment(0xeb, prefix + struct.pack('>I', 2) + store[:8] + store[split:])
    write('c2pa-split-generator.jpg', plain[:2] + first + second + plain[2:])

    # Extended XMP: an ordinary standard packet that references an extended packet
    # carrying the generative source type. The extended packet is sent in two chunks.
    extended = GENERATIVE_XMP
    guid = hashlib.md5(extended).hexdigest().upper().encode()
    standard = xmp('xmpNote:HasExtendedXMP="' + guid.decode() + '"',
                   'xmlns:xmpNote="http://ns.adobe.com/xmp/note/"')
    segments = [segment(0xe1, b'http://ns.adobe.com/xap/1.0/\0' + standard)]
    half = len(extended) // 2
    for offset, chunk in ((0, extended[:half]), (half, extended[half:])):
        segments.append(segment(0xe1, b'http://ns.adobe.com/xmp/extension/\0' + guid +
                                struct.pack('>II', len(extended), offset) + chunk))
    write('extended-xmp.jpg', plain[:2] + b''.join(segments) + plain[2:])
    write('extended-xmp-unreferenced.jpg', plain[:2] + b''.join(segments[1:]) + plain[2:])
    write('extended-xmp-out-of-order.jpg', plain[:2] +
          segments[0] + segments[2] + segments[1] + plain[2:])
    wrong_guid = b'0' * 32
    write('extended-xmp-bad-digest.jpg', plain[:2] +
          b''.join(packet.replace(guid, wrong_guid) for packet in segments) + plain[2:])

    # A duplicate chunk makes the old byte count reach the packet length even though
    # the latter part was never supplied. Put the declaration in the first chunk.
    incomplete = extended + b' ' * len(extended)
    broken_guid = hashlib.md5(incomplete).hexdigest().upper().encode()
    broken_ref = standard.replace(guid, broken_guid)
    duplicate = segment(0xe1, b'http://ns.adobe.com/xmp/extension/\0' + broken_guid +
                        struct.pack('>II', len(incomplete), 0) + extended)
    write('extended-xmp-overlap.jpg', plain[:2] +
          segment(0xe1, b'http://ns.adobe.com/xap/1.0/\0' + broken_ref) +
          duplicate + duplicate + plain[2:])


# ---------------------------------------------------------------- PNG


def png_chunk(kind, data):
    return struct.pack('>I', len(data)) + kind + data + struct.pack('>I', zlib.crc32(kind + data))


def png(text_chunks):
    ihdr = png_chunk(b'IHDR', struct.pack('>IIBBBBB', 2, 2, 8, 2, 0, 0, 0))
    idat = png_chunk(b'IDAT', zlib.compress(b'\0' + b'\x80' * 6 + b'\0' + b'\x80' * 6))
    return b'\x89PNG\r\n\x1a\n' + ihdr + b''.join(text_chunks) + idat + png_chunk(b'IEND', b'')


def text(key, value):
    return png_chunk(b'tEXt', key.encode() + b'\0' + value.encode())


def alpha_png(payload=b''):
    width, height = 32, 64
    pixels = bytearray(b'\x80\x80\x80\x80' * (width * height))
    assert len(payload) * 8 <= width * height
    for index in range(len(payload) * 8):
        bit = (payload[index // 8] >> (7 - index % 8)) & 1
        pixel = (index % height) * width + index // height
        pixels[pixel * 4 + 3] |= bit
    stride = width * 4
    scanlines = b''.join(b'\0' + pixels[row:row + stride] for row in range(0, len(pixels), stride))
    ihdr = png_chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
    return b'\x89PNG\r\n\x1a\n' + ihdr + png_chunk(b'IDAT', zlib.compress(scanlines)) + png_chunk(b'IEND', b'')


